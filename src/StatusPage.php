/**
 * Renders a {@see StatusReport} as a page a person reads.
 *
 * Two formats over one model, so a count cannot differ between them. Markdown is the testable one — it
 * diffs, it snapshots, and it renders wherever a repository is read. HTML is for looking at.
 *
 * Every number here carries its configuration, because the same count is correct twice over for different
 * targets and a reader with no target on the page concludes the tool is inconsistent.
 */
final class StatusPage
