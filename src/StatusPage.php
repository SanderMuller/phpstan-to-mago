    public static function markdown(StatusReport $report): string
    {
        $lines = [
            '# PHPStan rules on mago',
            '',
            sprintf(
                'GENERATED by phpstan-to-mago for the `%s` target. %d of %d portable rules run, across the %d '
                . 'rule packages installed here.',
                $report->target,
                $report->emitted(),
                $report->portable(),
                count($report->packages),
            ),
            '',
            'That denominator is this install. Any figure quoting a fixed set of packages counts something',
            'else, so two correct numbers will differ. The package list below is the configuration behind',
            'this one.',
            '',
            'A rule runs when this tool could translate its body. One that could not is listed below with the',
            'construct that stopped it, so the gap is legible rather than a number to take on trust. A refused',
            'rule still runs under PHPStan. It is only missing from mago.',
            '',
            '`ships` counts every rule class in the package. `registers` counts the ones it wires in a neon of',
            'its own. A rule it wires nowhere cannot run for anybody, whatever this tool does with it, so the',
            'coverage figure uses that smaller number. `refused` means not translated yet, and that gap can',
            'close. `never` marks a rule no plugin could carry, which is why it sits outside the denominator.',
            '',
            'These are *translation* numbers: whether this tool could carry a rule body across. They do not',
            'say what a rule finds. Some packages ship rules that report nothing until a project configures',
            'what they forbid, and those read as 0 here whether or not their bodies would translate. Whether',
            'a rule is worth carrying is a different question, and this page does not answer it.',
            '',
            sprintf('Generated %s. Re-run `%s` to update it.', $report->generatedAt, $report->command),
            '',
            '| package | version | ships | registers | runs | refused | never |',
            '|:--|:--|--:|--:|--:|--:|--:|',
        ];

        foreach ($report->packages as $package) {
            $lines[] = sprintf(
                '| `%s` | %s | %d | %d | %d | %d | %d |',
                $package->package,
                $report->versions[$package->package] ?? 'unknown',
                $package->ships(),
                count($package->registered()),
                $package->emitted(),
                $package->refused(),
                $package->never(),
            );
        }

        foreach ($report->packages as $package) {
            $lines[] = '';
            $lines[] = sprintf(
                '## %s — %d of %d run',
                $package->package,
                $package->emitted(),
                $package->portable(),
            );
            $lines[] = '';

            foreach ($package->registered() as $outcome) {
                if ($outcome->emitted()) {
                    $lines[] = 'RUNS    ' . $outcome->name;

                    continue;
                }

                // `NEVER` is not a gap to close. Those rules report nothing a plugin could carry, so no
                // vocabulary entry reaches them and a reader sizing work from this page should skip them.
                $label = $outcome->verdict === RuleOutcome::NEVER ? 'NEVER   ' : 'REFUSED ';
                $lines[] = $label . $outcome->name . "\n        " . $outcome->reason;
            }
        }

        return implode("\n", $lines) . "\n";
    }

